"""VGA 문자 층의 8x16 폰트 ROM 생성 → hdl/font8x16.v, nios/glyphs.h

- 0x20~0x7E: DejaVu Sans Mono(matplotlib에 들어 있는 자유 라이선스 글꼴)를 1비트로 그린다.
- 0x01~0x08: 왼쪽부터 1/8 ~ 8/8칸을 채운 막대 조각. 막대 그래프를 1픽셀 단위로 그리는 데 쓴다.
- 0x10~0x17: 테두리 선과 네모. 0x18~0x1F: 여덟 방향 화살표(기울기 방향 표시).
ROM 내용은 Verilog initial 블록으로 내보낸다. 그래서 Quartus와 ModelSim이 같은 파일 하나만 읽고,
$readmemh의 경로 문제가 없다. 생성된 파일도 저장소에 넣어 두므로 빌드에 이 스크립트가 필요하지 않다.

실행: python pc/gen_font.py            두 파일을 다시 만든다
      python pc/gen_font.py --check    저장소의 파일이 이 스크립트 출력과 같은지 확인
      python pc/gen_font.py --sheet 파일.png   글자표 그림 저장(눈으로 확인용)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
W, H = 8, 16

# 이름 → 코드. nios/glyphs.h로도 내보낸다.
GLYPHS = {"BAR1": 0x01, "BAR8": 0x08, "HLINE": 0x10, "VLINE": 0x11, "TL": 0x12, "TR": 0x13, "BL": 0x14, "BR": 0x15,
          "SQ_FULL": 0x16, "SQ_EMPTY": 0x17, "ARROW_E": 0x18}
ARROWS = "→↗↑↖←↙↓↘"     # E NE N NW W SW S SE (반시계 45도씩)


def blank():
    return [[0] * W for _ in range(H)]


def rect(g, x0, y0, w, h):
    for y in range(y0, y0 + h):
        for x in range(x0, x0 + w):
            g[y][x] = 1
    return g


def custom():
    """목업(docs/vga-ui-mockup.html)의 그리기 코드와 같은 모양"""
    out = {}
    for n in range(1, 9):
        out[n] = rect(blank(), 0, 3, n, H - 6)
    segs = {0x10: (1, 1, 0, 0), 0x11: (0, 0, 1, 1), 0x12: (0, 1, 0, 1), 0x13: (1, 0, 0, 1), 0x14: (0, 1, 1, 0), 0x15: (1, 0, 1, 0)}
    for code, (left, right, up, down) in segs.items():
        g = blank()
        if left:
            rect(g, 0, 8, 4, 1)
        if right:
            rect(g, 4, 8, 4, 1)
        if up:
            rect(g, 4, 0, 1, 8)
        if down:
            rect(g, 4, 8, 1, 8)
        g[8][4] = 1
        out[code] = g
    out[0x16] = rect(blank(), 1, 4, 6, 8)
    g = blank()
    rect(g, 1, 4, 6, 1), rect(g, 1, 11, 6, 1), rect(g, 1, 4, 1, 8), rect(g, 6, 4, 1, 8)
    out[0x17] = g
    return out


def from_ttf(chars):
    import matplotlib
    from PIL import Image, ImageDraw, ImageFont
    path = os.path.join(os.path.dirname(matplotlib.__file__), "mpl-data", "fonts", "ttf", "DejaVuSansMono.ttf")
    font = ImageFont.truetype(path, 13)          # 13 px: 글자 폭이 8픽셀에 맞는다
    out = {}
    for code, ch in chars.items():
        img = Image.new("1", (W, H), 0)
        d = ImageDraw.Draw(img)
        d.fontmode = "1"                          # 안티에일리어싱 없이 1비트로
        d.text((0, 0), ch, fill=1, font=font)
        out[code] = [[1 if img.getpixel((x, y)) else 0 for x in range(W)] for y in range(H)]
    return out


def build():
    chars = {c: chr(c) for c in range(0x21, 0x7F)}
    chars.update({0x18 + i: a for i, a in enumerate(ARROWS)})
    table = {c: blank() for c in range(128)}
    table.update(from_ttf(chars))
    table.update(custom())
    return [sum(bit << (7 - x) for x, bit in enumerate(table[c][y])) for c in range(128) for y in range(H)]


def verilog(rom):
    lines = ["// font8x16.v - 8x16 font ROM for hdl/vga_ui.v. Generated by pc/gen_font.py, do not edit.",
             "// Address = {character[6:0], row[3:0]}. Data bit 7 is the leftmost pixel.",
             "// 0x20..0x7E: DejaVu Sans Mono (free licence). 0x01..0x1F: bar pieces, frame lines, arrows.",
             "// Quartus builds this table from logic cells (about 800), not from a memory block,",
             "// which suits this design: memory blocks are nearly used up, logic cells are not.",
             "module font8x16 (input clk, input [10:0] addr, output reg [7:0] q);",
             "    reg [7:0] rom [0:2047];",
             "    always @(posedge clk) q <= rom[addr];",
             "    initial begin"]
    lines += ["        rom[%d] = 8'h%02X;" % (i, v) for i, v in enumerate(rom)]
    lines += ["    end", "endmodule", ""]
    return "\n".join(lines)


def header():
    lines = ["/* glyphs.h - character codes of the special glyphs in hdl/font8x16.v.",
             " * Generated by pc/gen_font.py, do not edit. */",
             "#ifndef GLYPHS_H", "#define GLYPHS_H"]
    lines += ["#define G_%s 0x%02X" % (k, v) for k, v in GLYPHS.items()]
    lines += ["#endif", ""]
    return "\n".join(lines)


def sheet(rom, path):
    from PIL import Image
    img = Image.new("L", (16 * W * 3, 8 * H * 3), 40)
    for c in range(128):
        for y in range(H):
            for x in range(W):
                if rom[c * H + y] >> (7 - x) & 1:
                    for dy in range(3):
                        for dx in range(3):
                            img.putpixel(((c % 16) * W * 3 + x * 3 + dx, (c // 16) * H * 3 + y * 3 + dy), 255)
    img.save(path)


def main():
    rom = build()
    assert len(rom) == 2048
    assert rom[0x08 * 16 + 5] == 0xFF and rom[0x01 * 16 + 5] == 0x80 and rom[0x08 * 16 + 2] == 0   # 막대 조각
    assert any(rom[ord("A") * 16:ord("A") * 16 + 16]) and not any(rom[0x20 * 16:0x20 * 16 + 16])
    files = {os.path.join(HERE, "..", "hdl", "font8x16.v"): verilog(rom),
             os.path.join(HERE, "..", "nios", "glyphs.h"): header()}
    if "--sheet" in sys.argv:
        sheet(rom, sys.argv[sys.argv.index("--sheet") + 1])
    if "--check" in sys.argv:
        for p, text in files.items():
            assert open(p, newline="").read().replace("\r\n", "\n") == text, "%s is stale: run pc/gen_font.py" % p
        print("gen_font OK")
        return
    for p, text in files.items():
        with open(p, "w", newline="\n") as f:
            f.write(text)
    print("wrote font8x16.v, glyphs.h")


if __name__ == "__main__":
    main()
